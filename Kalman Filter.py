def get_trilateration_2d(p1, p2, p3, d1, d2, d3):
    """
    Mencari posisi (x, y) menggunakan metode trilaterasi.

    Args:
        p1, p2, p3: Tuple/List (x, y) posisi masing-masing anchor.
        d1, d2, d3: Jarak (radius) dari masing-masing anchor.
    """
    x1, y1 = p1
    x2, y2 = p2
    x3, y3 = p3

    # Persamaan sistem linear dari perpotongan lingkaran
    A = 2*x2 - 2*x1
    B = 2*y2 - 2*y1
    C = d1**2 - d2**2 - x1**2 + x2**2 - y1**2 + y2**2
    D = 2*x3 - 2*x2
    E = 2*y3 - 2*y2
    F = d2**2 - d3**2 - x2**2 + x3**2 - y2**2 + y3**2

    # Menghitung titik x dan y menggunakan determinan
    denominator = (A*E - B*D)
    if abs(denominator) < 1e-9:
        return None # Anchor sejajar, tidak bisa dihitung

    x = (C*E - F*B) / denominator
    y = (A*F - D*C) / denominator

    return x, y

