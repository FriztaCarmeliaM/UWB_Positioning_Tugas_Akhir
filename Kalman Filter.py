def apply_kalman_filter(measurements, Q=0.001, R=100):
    """
    Applies a 1D Kalman Filter to a series of measurements.

    Args:
        measurements (array-like): The observed data from the sensor.
        Q (float): Process Noise. Controls how much the model trusts its prediction.
                   Smaller Q means more trust in the prediction.
        R (float): Measurement Noise. Controls how much the model trusts the new measurement.
                   Smaller R means more trust in the measurement.

    Returns:
        list: The Kalman Filtered estimates.
    """
    if len(measurements) == 0:
        return []

    # Tebakan awal sistem
    x_estimasi = measurements[0]  # Kita mulai tebakan dari titik data pertama
    P = 1.0  # Tingkat keraguan awal kita (Error Covariance)

    hasil_kalman = []

    for z in measurements:
        # --- TAHAP 1: PREDIKSI ---
        x_prediksi = x_estimasi  # Model sederhana: tebak posisi tetap sama dengan sebelumnya
        P_prediksi = P + Q

        # --- TAHAP 2: KOREKSI (UPDATE) ---
        K = P_prediksi / (P_prediksi + R)  # Menghitung "Kalman Gain" (Bobot Kepercayaan)
        x_estimasi = x_prediksi + K * (z - x_prediksi)
        P = (1 - K) * P_prediksi  # Update tingkat keraguan untuk iterasi berikutnya

        hasil_kalman.append(x_estimasi)

    return hasil_kalman

